def to_snake(name: str) -> str:
    if name in RUST_KEYWORDS:
        return RUST_KEYWORDS[name]
    out = []
    for i, ch in enumerate(name):
        if ch.isupper():
            prev_lower = i > 0 and name[i - 1].islower()
            next_lower = i + 1 < len(name) and name[i + 1].islower()
            if i > 0 and (prev_lower or (name[i - 1].isupper() and next_lower)):
                out.append("_")
            out.append(ch.lower())
        else:
            out.append(ch)
    res = "".join(out)
    return RUST_KEYWORDS.get(res, res)


def field_name(var: VkVariable) -> str:
    return to_snake(var.name)


def resolve_base(ty: VkType) -> VkType:
    while ty.category in (VkType.BASETYPE, VkType.BITMASK) and ty.typedef:
        ty = ty.typedef
    return ty


def is_serializable(var: VkVariable | VkType) -> bool:
    if isinstance(var, VkType):
        return is_serializable(VkVariable(var))
    ty = resolve_base(var.ty.base)
    if ty.category in (ty.INCLUDE, ty.DEFINE, ty.FUNCPOINTER):
        return False
    if ty.category == ty.DEFAULT:
        if ty.name in PRIMITIVE_TYPES or ty.name in ("char", "size_t"):
            return True
        if ty.name == "void":
            return var.is_blob()
        return False
    if ty.category in (ty.HANDLE, ty.ENUM, ty.BITMASK):
        return True
    if ty.category == ty.UNION:
        return ty.is_valid_union() or ty.name in UNION_DEFAULT_TAGS
    if ty.category == ty.STRUCT:
        if ty.name in ("VkBaseInStructure", "VkBaseOutStructure"):
            return False
    elif ty.category == ty.COMMAND:
        if ty.name in COMMAND_BLOCK_LIST:
            return False
        if ty.ret and not is_serializable(ty.ret):
            return False
    for m in ty.variables:
        if m.maybe_null() or m.is_p_next():
            continue
        if not is_serializable(m):
            return False
    return True


def get_chain(ty: VkType) -> list[VkType]:
    return [nxt for nxt in ty.p_next if is_serializable(nxt)]


def fixup_registry(reg: VkRegistry, supported: set[VkType]) -> VkRegistry:
    reg = copy.deepcopy(reg)
    for ty in reg.type_table.values():
        if ty.category == ty.COMMAND:
            ty.attrs["c_type"] = "VK_COMMAND_TYPE_" + ty.name + "_EXT"
            if ty.ret:
                ty.ret.attrs["var_out"] = True
            for var in ty.variables:
                if var.ty.is_pointer() and not var.ty.is_const_pointer():
                    var.attrs["var_out"] = True
                else:
                    var.attrs["var_in"] = True
            for var in ty.variables:
                for name in var.attrs.get("len_names", []):
                    v = ty.find_variables(name)
                    if v and "var_out" in v[0].attrs:
                        v[0].attrs["var_in"] = var
                        v[0].attrs["var_out"] = var
            if ty.name == "vkRegisterCustomBorderColorEXT":
                for var in ty.variables:
                    if var.name == "pIndex":
                        var.attrs["var_in"] = True
    # Filter p_next to supported types
    sup_names = {t.name for t in supported}
    for ty in reg.type_table.values():
        if ty.name in sup_names:
            ty.p_next = [p for p in ty.p_next if p.name in sup_names]
    return reg


def emit_api_constants(vk_xml: Path) -> str:
    tree = ET.parse(vk_xml)
    root = tree.getroot()
    lines = [BANNER]
    seen: set[str] = set()
    for enums in root.findall("enums"):
        if enums.attrib.get("name") != "API Constants":
            continue
        for enum in enums.findall("enum"):
            name = enum.attrib["name"]
            if name in seen:
                continue
            seen.add(name)
            if "alias" in enum.attrib:
                target = enum.attrib["alias"]
                # Infer type from target
                if target in ("VK_LOD_CLAMP_NONE",):
                    lines.append(f"pub const {name}: f32 = {target};\n")
                elif target in ("VK_WHOLE_SIZE", "VK_QUEUE_FAMILY_EXTERNAL", "VK_SUBPASS_EXTERNAL", "VK_ATTACHMENT_UNUSED", "VK_QUEUE_FAMILY_IGNORED", "VK_REMAINING_MIP_LEVELS", "VK_REMAINING_ARRAY_LAYERS", "VK_SHADER_UNUSED_KHR"):
                    rty = "u64" if target == "VK_WHOLE_SIZE" else "u32"
                    lines.append(f"pub const {name}: {rty} = {target};\n")
                else:
                    lines.append(f"pub const {name}: usize = {target};\n")
                continue
            val = enum.attrib["value"].strip()
            if val == "(~0U)":
                lines.append(f"pub const {name}: u32 = u32::MAX;\n")
            elif val == "(~1U)":
                lines.append(f"pub const {name}: u32 = u32::MAX - 1;\n")
            elif val == "(~2U)":
                lines.append(f"pub const {name}: u32 = u32::MAX - 2;\n")
            elif val == "(~0ULL)":
                lines.append(f"pub const {name}: u64 = u64::MAX;\n")
            elif val.endswith(("F", "f")):
                lines.append(f"pub const {name}: f32 = {val[:-1]}_f32;\n")
            elif val.endswith("ULL"):
                lines.append(f"pub const {name}: u64 = {val[:-3]};\n")
            elif val.endswith("U"):
                lines.append(f"pub const {name}: u32 = {val[:-1]};\n")
            else:
                lines.append(f"pub const {name}: usize = {val};\n")
    return "".join(lines)


def rust_base_type(ty: VkType) -> str:
    if ty.category == ty.BASETYPE:
        if ty.name in ("VkSampleMask", "VkBool32", "VkFlags", "VkFlags64", "VkDeviceSize", "VkDeviceAddress"):
            return ty.name
        if ty.typedef:
            return rust_base_type(ty.typedef)
    if ty.category in (ty.HANDLE, ty.ENUM, ty.BITMASK, ty.STRUCT, ty.UNION):
        return ty.name
    if ty.name in PRIMITIVE_TYPES:
        return PRIMITIVE_TYPES[ty.name][0]
    if ty.name == "size_t":
        return "u64"
    if ty.name == "char":
        return "u8"
    return "u32"


def dim_to_rust(dim: str) -> str:
    if dim == "3][4":
        return ""  # handled specially
    return dim


def var_rust_type(parent_name: str, var: VkVariable) -> str | None:
    if var.is_p_next():
        return None
    if not is_serializable(var):
        return None
    base = var.ty.base
    # Static array
    if var.ty.is_static_array():
        dim = var.ty.decor.dim
        elem = rust_base_type(base)
        if dim == "3][4":
            return f"[[{elem}; 4]; 3]"
        return f"[{elem}; {dim}]"
    # Dynamic array / string / blob / pointer
    if var.ty.is_pointer():
        if var.has_c_string():
            if var.ty.indirection_depth() >= 2:
                return "Vec<String>"
            return "Option<String>"
        if var.is_blob():
            return "Vec<u8>"
        if var.ty.indirection_depth() >= 2:
            return f"Vec<Vec<{rust_base_type(base)}>>"
        if var.is_dynamic_array():
            return f"Vec<{rust_base_type(base)}>"
        return f"Option<Box<{rust_base_type(base)}>>"
    # Scalar / struct / union / handle / enum / bitmask
    return rust_base_type(base)


def emit_len_expr(expr: str, vars_in_scope: dict[str, VkVariable], prefix: str) -> str:
    expr = expr.strip()
    if expr == "1":
        return "1usize"
    if expr == "2*VK_UUID_SIZE":
        return "(2 * VK_UUID_SIZE)"
    if expr == "codeSize / 4":
        return f"(({prefix}code_size / 4) as usize)"
    if expr == "(rasterizationSamples + 31) / 32":
        return f"((({prefix}rasterization_samples.0 as usize) + 31) / 32)"
    if expr == "(samples + 31) / 32":
        return f"((({prefix}samples.0 as usize) + 31) / 32)"
    if "->" in expr:
        lhs, rhs = expr.split("->", 1)
        lhs_s = to_snake(lhs)
        rhs_s = to_snake(rhs)
        return f"({prefix}{lhs_s}.as_ref().map_or(0, |x| x.{rhs_s}) as usize)"
    if "[i]." in expr:
        return "0usize"
    if expr in vars_in_scope:
        v = vars_in_scope[expr]
        fn = f"{prefix}{field_name(v)}"
        if v.ty.is_pointer():
            return f"(*{fn}.as_deref().unwrap_or(&0) as usize)"
        return f"({fn} as usize)"
    return f"({to_snake(expr)} as usize)"


def emit_scalar_decode(ty: VkType) -> str:
    r = resolve_base(ty)
    if r.name in PRIMITIVE_TYPES:
        return f"dec.{PRIMITIVE_TYPES[r.name][1]}()?"
    if r.name == "size_t":
        return "dec.read_size_t()?"
    if r.name == "char":
        return "dec.read_u8()?"
    if ty.category in (ty.HANDLE, ty.ENUM):
        return f"{ty.name}::decode(dec)?"
    if ty.category == ty.BITMASK:
        if r.name == "uint64_t":
            return "dec.read_u64()?"
        return "dec.read_u32()?"
    return f"{ty.name}::decode(dec)?"


def emit_scalar_encode(ty: VkType, expr: str) -> str:
    r = resolve_base(ty)
    if r.name in PRIMITIVE_TYPES:
        return f"enc.{PRIMITIVE_TYPES[r.name][2]}({expr})?"
    if r.name == "size_t":
        return f"enc.write_size_t({expr})?"
    if r.name == "char":
        return f"enc.write_u8({expr})?"
    if ty.category in (ty.HANDLE, ty.ENUM):
        return f"({expr}).encode(enc)?"
    if ty.category == ty.BITMASK:
        if r.name == "uint64_t":
            return f"enc.write_u64({expr})?"
        return f"enc.write_u32({expr})?"
    return f"({expr}).encode(enc)?"


def emit_struct_decode_member(
    ty: VkType,
    var: VkVariable,
    vars_map: dict[str, VkVariable],
    partial: bool,
    indent: str = "        ",
) -> list[str]:
    lines: list[str] = []
    fn = field_name(var)
    if var.is_p_next():
        return lines
    if not is_serializable(var):
        if var.ty.is_pointer():
            lines.append(f"{indent}if dec.read_simple_pointer()? {{ return Err(WireError::InvalidPointerFlag(1)); }}\n")
        return lines

    if partial:
        # Partial out-struct: only array sizes / pointers / sType / pNext are decoded; scalars are skipped
        if var.ty.is_pointer():
            if var.is_dynamic_array():
                lines.append(f"{indent}let _ = dec.read_array_size_unchecked()?;\n")
            else:
                lines.append(f"{indent}let _ = dec.read_simple_pointer()?;\n")
        return lines

    return emit_struct_decode_member_uncond(ty, var, vars_map, indent)


def emit_struct_decode_member_uncond(
    ty: VkType,
    var: VkVariable,
    vars_map: dict[str, VkVariable],
    indent: str = "        ",
) -> list[str]:
    lines: list[str] = []
    fn = field_name(var)

    base = var.ty.base
    if var.ty.is_static_array():
        dim = var.ty.decor.dim
        if dim == "3][4":
            lines.append(
                f"{indent}let mut {fn} = [[0.0_f32; 4]; 3];\n"
                f"{indent}for row in &mut {fn} {{ for cell in row {{ *cell = dec.read_f32()?; }} }}\n"
            )
        elif base.name == "char":
            lines.append(
                f"{indent}let mut {fn} = [0u8; {dim}];\n"
                f"{indent}{fn}.copy_from_slice(dec.read_blob({dim})?);\n"
            )
        else:
            lines.append(
                f"{indent}let mut {fn} = core::array::from_fn(|_| Default::default());\n"
                f"{indent}for item in &mut {fn} {{ *item = {emit_scalar_decode(base)}; }}\n"
            )
        return lines

    if var.ty.is_pointer():
        if var.has_c_string():
            if var.ty.indirection_depth() >= 2:
                lines.append(
                    f"{indent}let {fn}_arr_sz = dec.read_array_size_unchecked()?;\n"
                    f"{indent}let mut {fn} = Vec::with_capacity({fn}_arr_sz as usize);\n"
                    f"{indent}for _ in 0..{fn}_arr_sz {{\n"
                    f"{indent}    let s_len = dec.read_array_size_unchecked()?;\n"
                    f"{indent}    {fn}.push(if s_len == 0 {{ String::new() }} else {{ dec.read_string(s_len as usize)? }});\n"
                    f"{indent}}}\n"
                )
            else:
                lines.append(
                    f"{indent}let {fn}_sz = dec.read_array_size_unchecked()?;\n"
                    f"{indent}let {fn} = if {fn}_sz == 0 {{ None }} else {{ Some(dec.read_string({fn}_sz as usize)?) }};\n"
                )
            return lines
        if var.is_blob():
            lines.append(
                f"{indent}let {fn}_sz = dec.read_array_size_unchecked()?;\n"
                f"{indent}let {fn} = if {fn}_sz == 0 {{ Vec::new() }} else {{ dec.read_blob({fn}_sz as usize)?.to_vec() }};\n"
            )
            return lines
        if var.ty.indirection_depth() >= 2:
            lines.append(
                f"{indent}let {fn}_outer = dec.read_array_size_unchecked()?;\n"
                f"{indent}let mut {fn} = Vec::with_capacity({fn}_outer as usize);\n"
                f"{indent}for _ in 0..{fn}_outer {{\n"
                f"{indent}    let inner_sz = dec.read_array_size_unchecked()?;\n"
                f"{indent}    let mut inner = Vec::with_capacity(inner_sz as usize);\n"
                f"{indent}    for _ in 0..inner_sz {{ inner.push({emit_scalar_decode(base)}); }}\n"
                f"{indent}    {fn}.push(inner);\n"
                f"{indent}}}\n"
            )
            return lines
        if var.is_dynamic_array():
            r = resolve_base(base)
            if r.name == "uint8_t":
                lines.append(
                    f"{indent}let {fn}_sz = dec.read_array_size_unchecked()?;\n"
                    f"{indent}let {fn} = if {fn}_sz == 0 {{ Vec::new() }} else {{ dec.read_u8_slice({fn}_sz as usize)?.to_vec() }};\n"
                )
            else:
                lines.append(
                    f"{indent}let {fn}_sz = dec.read_array_size_unchecked()?;\n"
                    f"{indent}let mut {fn} = Vec::with_capacity({fn}_sz as usize);\n"
                    f"{indent}for _ in 0..{fn}_sz {{ {fn}.push({emit_scalar_decode(base)}); }}\n"
                )
            return lines
        # Simple pointer
        lines.append(
            f"{indent}let {fn} = if dec.read_simple_pointer()? {{ Some(Box::new({emit_scalar_decode(base)})) }} else {{ None }};\n"
        )
        return lines

    lines.append(f"{indent}let {fn} = {emit_scalar_decode(base)};\n")
    return lines


def emit_struct_encode_member(
    ty: VkType,
    var: VkVariable,
    vars_map: dict[str, VkVariable],
    partial: bool,
    prefix: str = "self.",
    indent: str = "        ",
) -> list[str]:
    lines: list[str] = []
    fn = field_name(var)
    if var.is_p_next():
        return lines
    if not is_serializable(var):
        if var.ty.is_pointer():
            lines.append(f"{indent}enc.write_simple_pointer(false)?;\n")
        return lines

    if partial:
        if var.ty.is_pointer():
            if var.has_c_string() and var.ty.indirection_depth() == 1:
                lines.append(f"{indent}enc.write_array_size({prefix}{fn}.as_ref().map_or(0, |s| s.len() + 1) as u64)?;\n")
            elif var.is_dynamic_array():
                lines.append(f"{indent}enc.write_array_size({prefix}{fn}.len() as u64)?;\n")
            else:
                lines.append(f"{indent}enc.write_simple_pointer({prefix}{fn}.is_some())?;\n")
        return lines

    return emit_struct_encode_member_uncond(ty, var, vars_map, prefix, indent)


def emit_struct_encode_member_uncond(
    ty: VkType,
    var: VkVariable,
    vars_map: dict[str, VkVariable],
    prefix: str = "self.",
    indent: str = "        ",
) -> list[str]:
    lines: list[str] = []
    fn = field_name(var)

    base = var.ty.base
    if var.ty.is_static_array():
        dim = var.ty.decor.dim
        if dim == "3][4":
            lines.append(
                f"{indent}for row in &{prefix}{fn} {{ for &cell in row {{ enc.write_f32(cell)?; }} }}\n"
            )
        elif base.name == "char":
            lines.append(f"{indent}enc.write_blob(&{prefix}{fn})?;\n")
        else:
            ref = "&" if prefix else ""
            lines.append(
                f"{indent}for item in {ref}{prefix}{fn} {{ {emit_scalar_encode(base, '*item' if base.category != base.STRUCT and base.category != base.UNION else 'item')} }}\n"
            )
        return lines

    if var.ty.is_pointer():
        if var.has_c_string():
            if var.ty.indirection_depth() >= 2:
                lines.append(
                    f"{indent}enc.write_array_size({prefix}{fn}.len() as u64)?;\n"
                    f"{indent}for s in &{prefix}{fn} {{\n"
                    f"{indent}    let bytes = s.as_bytes();\n"
                    f"{indent}    enc.write_array_size((bytes.len() + 1) as u64)?;\n"
                    f"{indent}    let mut buf = Vec::with_capacity(bytes.len() + 1);\n"
                    f"{indent}    buf.extend_from_slice(bytes);\n"
                    f"{indent}    buf.push(0);\n"
                    f"{indent}    enc.write_cstr_bytes(&buf)?;\n"
                    f"{indent}}}\n"
                )
            else:
                lines.append(
                    f"{indent}match &{prefix}{fn} {{\n"
                    f"{indent}    None => enc.write_array_size(0)?,\n"
                    f"{indent}    Some(s) => {{\n"
                    f"{indent}        let bytes = s.as_bytes();\n"
                    f"{indent}        enc.write_array_size((bytes.len() + 1) as u64)?;\n"
                    f"{indent}        let mut buf = Vec::with_capacity(bytes.len() + 1);\n"
                    f"{indent}        buf.extend_from_slice(bytes);\n"
                    f"{indent}        buf.push(0);\n"
                    f"{indent}        enc.write_cstr_bytes(&buf)?;\n"
                    f"{indent}    }}\n"
                    f"{indent}}}\n"
                )
            return lines
        if var.is_blob():
            lines.append(
                f"{indent}enc.write_array_size({prefix}{fn}.len() as u64)?;\n"
                f"{indent}if !{prefix}{fn}.is_empty() {{ enc.write_blob(&{prefix}{fn})?; }}\n"
            )
            return lines
        if var.ty.indirection_depth() >= 2:
            lines.append(
                f"{indent}enc.write_array_size({prefix}{fn}.len() as u64)?;\n"
                f"{indent}for inner in &{prefix}{fn} {{\n"
                f"{indent}    enc.write_array_size(inner.len() as u64)?;\n"
                f"{indent}    for item in inner {{ {emit_scalar_encode(base, '*item' if base.category != base.STRUCT and base.category != base.UNION else 'item')} }}\n"
                f"{indent}}}\n"
            )
            return lines
        if var.is_dynamic_array():
            r = resolve_base(base)
            if r.name == "uint8_t":
                lines.append(
                    f"{indent}enc.write_array_size({prefix}{fn}.len() as u64)?;\n"
                    f"{indent}if !{prefix}{fn}.is_empty() {{ enc.write_u8_slice(&{prefix}{fn})?; }}\n"
                )
            else:
                lines.append(
                    f"{indent}enc.write_array_size({prefix}{fn}.len() as u64)?;\n"
                    f"{indent}for item in &{prefix}{fn} {{ {emit_scalar_encode(base, '*item' if base.category != base.STRUCT and base.category != base.UNION else 'item')} }}\n"
                )
            return lines
        # Simple pointer
        val_expr = "v" if base.category in (base.STRUCT, base.UNION) else "**v"
        lines.append(
            f"{indent}match &{prefix}{fn} {{\n"
            f"{indent}    None => enc.write_simple_pointer(false)?,\n"
            f"{indent}    Some(v) => {{ enc.write_simple_pointer(true)?; {emit_scalar_encode(base, val_expr)}; }}\n"
            f"{indent}}}\n"
        )
        return lines

    lines.append(f"{indent}{emit_scalar_encode(base, f'{prefix}{fn}')};\n")
    return lines
